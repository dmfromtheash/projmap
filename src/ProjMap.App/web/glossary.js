function splitWords(name, isFile = false) {
  return (isFile ? name.replace(/\.[a-z0-9]+$/i, '') : name)
    .split(/[.\-_/\s]+/)
    .flatMap(p => p.split(/(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])/))
    .filter(Boolean);
}

/** Russian role for a node: { ru: short name or null, hint: explanation or null }. */
function describe(node, projectName) {
  const name = node.name || '';
  const lower = name.toLowerCase();
  if (node.kind === 'system') return { ru: 'Проект', hint: null };
  if (node.kind === 'group') {
    if (/data|баз/i.test(node.id + name)) return { ru: 'База данных', hint: 'таблицы, в которых программа хранит данные' };
    if (/doc/i.test(node.id + name)) return { ru: 'Документы', hint: 'все описания и планы проекта' };
    if (/road|план/i.test(node.id + name)) return { ru: 'План', hint: 'дорожная карта и задачи' };
  }
  if (node.kind === 'table') return { ru: 'Таблица', hint: 'хранит записи в базе данных' };
  if (SPECIAL_FILES[lower]) return { ru: null, hint: SPECIAL_FILES[lower] };

  if (node.kind === 'module' || node.kind === 'folder') {
    const proj = (projectName || '').toLowerCase();
    // a known whole segment ("LiveCheck") wins over its camel-case pieces ("Live", "Check")
    let segs = name.replace(/^\./, '').split(/[.\-_/\s]+/).filter(Boolean);
    if (segs.length > 1 && segs[0].toLowerCase() === proj) segs = segs.slice(1);
    const words = segs.flatMap(s => GLOSSARY[s.toLowerCase()] ? [s] : splitWords(s));
    const whole = GLOSSARY[name.replace(/[.\-_]/g, '').toLowerCase()];
    if (whole) return { ru: whole[0], hint: whole[1] };
    const parts = words.map(w => GLOSSARY[w.toLowerCase()]);
    if (!parts.some(Boolean)) return { ru: null, hint: null };
    const isTest = /^tests?$/i.test(words[words.length - 1]);
    const main = words.filter(w => !/^tests?$/i.test(w)).map(w => GLOSSARY[w.toLowerCase()]?.[0] || w).join(' · ');
    if (isTest) return { ru: main ? `Проверки: ${main}` : 'Проверки', hint: `автоматические тесты${main ? ' для части «' + main + '»' : ''}` };
    const last = [...parts].reverse().find(Boolean);
    return { ru: main, hint: last ? last[1] : null };
  }

  if (node.kind === 'file' || node.kind === 'type') {
    const base = name.replace(/\.[a-z0-9]+$/i, '');
    const role = SUFFIX_ROLE.find(([re]) => re.test(base));
    if (role) {
      const subject = base.replace(role[0], '');
      const subj = subject ? splitWords(subject, true).map(w => GLOSSARY[w.toLowerCase()]?.[0]?.toLowerCase() || w).join(' ') : '';
      return { ru: null, hint: subj ? `${role[1]}: ${subj}` : role[1] };
    }
  }
  return { ru: null, hint: null };
}
